// Builds README.md and docs/index.html from skills.json.
// Usage: node scripts/build.mjs [--refresh]   (--refresh pulls live star counts from the GitHub API)
import fs from 'node:fs';
const skills = JSON.parse(fs.readFileSync('skills.json', 'utf8'));
const cacheFile = 'stars.json';
let stars = fs.existsSync(cacheFile) ? JSON.parse(fs.readFileSync(cacheFile, 'utf8')) : {};
if (process.argv.includes('--refresh')) {
  const headers = { 'User-Agent': 'awesome-claude-skills-gallery' };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  for (const repo of [...new Set(skills.map(s => s.repo))]) {
    const r = await fetch(`https://api.github.com/repos/${repo}`, { headers });
    if (!r.ok) { console.error(`FAIL ${repo}: ${r.status}`); process.exitCode = 1; continue; }
    const j = await r.json();
    stars[repo] = { stars: j.stargazers_count, license: j.license?.spdx_id ?? null, archived: j.archived };
  }
  for (const s of skills.filter(s => s.path)) {
    const r = await fetch(`https://api.github.com/repos/${s.repo}/contents/${s.path}/SKILL.md`, { headers });
    if (!r.ok) { console.error(`MISSING ${s.repo}/${s.path}/SKILL.md: ${r.status}`); process.exitCode = 1; }
  }
  stars._updated = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(cacheFile, JSON.stringify(stars, null, 2) + '\n');
}
const url = s => `https://github.com/${s.repo}${s.path ? `/tree/main/${s.path}` : ''}`;
const fmt = n => n >= 1000 ? `${(n / 1000).toFixed(1)}k` : String(n);
const cats = [...new Set(skills.map(s => s.category))];
const slug = c => c.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-');
const esc = t => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

let md = `# Awesome Claude Skills Gallery [![Awesome](https://awesome.re/badge.svg)](https://awesome.re)

> See what agent skills actually produce before you install them.

Every entry links to a real, public skill. Screenshots are either generated by this repo by running the skill's own code, or taken from the skill's own repo with credit. Star counts are refreshed manually for now (last update: ${stars._updated ?? 'n/a'}); a daily GitHub Action is ready but not enabled yet.

Browse the visual version at [omrigotlieb.github.io/awesome-claude-skills-gallery](https://omrigotlieb.github.io/awesome-claude-skills-gallery/).

<p align="center"><img src="docs/assets/gallery/algorithmic-art.png" alt="Output of the algorithmic-art skill" width="720"></p>

## Contents

${cats.map(c => `- [${c}](#${slug(c)})`).join('\n')}
- [Related](#related)

`;
for (const c of cats) {
  md += `## ${c}\n\n`;
  for (const s of skills.filter(x => x.category === c)) {
    const st = stars[s.repo]?.stars;
    md += `- [${s.name}](${url(s)}) - ${s.desc.replace(/\.$/, '')}${st ? ` (${s.repo}, ${fmt(st)} stars)` : ''}.\n`;
    if (s.image) md += `\n  <img src="${s.image}" alt="${esc(s.name)} output" width="480">\n\n  *${s.imageCredit}*\n\n`;
  }
  md += '\n';
}
md += `## Related

- [awesome-anthropic](https://github.com/Omrigotlieb/awesome-anthropic) - Daily-updated list of Anthropic and Claude resources.
- [ai-skills](https://github.com/Omrigotlieb/ai-skills) - Ready-to-use skill and CLAUDE.md templates.
- [founder-deck-skill](https://github.com/Omrigotlieb/founder-deck-skill) - Agent skill that turns founder notes into an HTML pitch deck.
- [mcp-solo-founder](https://github.com/Omrigotlieb/mcp-solo-founder) - MCP server and skills for running a one-person company.
- [claude-md-doctor](https://github.com/Omrigotlieb/claude-md-doctor) - Lint and score your CLAUDE.md out of 100.

## Contributing

Contributions welcome. Read the [contribution guidelines](CONTRIBUTING.md) first.
`;
fs.writeFileSync('README.md', md.replace(/\n{3,}/g, '\n\n'));

const img = s => !s.image ? `<div class="noimg">No screenshot yet. <a href="https://github.com/Omrigotlieb/awesome-claude-skills-gallery/blob/main/CONTRIBUTING.md">Add one</a></div>`
  : `<img loading="lazy" src="${s.image.replace(/^docs\//, '')}" alt="${esc(s.name)} output">`;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Awesome Claude Skills Gallery</title><meta name="description" content="See what agent skills actually produce before you install them.">
<style>body{font-family:system-ui,sans-serif;background:#faf9f5;color:#1f1e1d;margin:0}header{padding:48px 24px 16px;max-width:1100px;margin:auto}h1{margin:0 0 8px}
.f{display:flex;gap:8px;flex-wrap:wrap;margin:16px 0}.f button{border:1px solid #d97757;background:#fff;color:#d97757;border-radius:20px;padding:6px 14px;cursor:pointer}.f button.on{background:#d97757;color:#fff}
main{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:20px;max-width:1100px;margin:auto;padding:0 24px 48px}
.c{background:#fff;border-radius:12px;box-shadow:0 1px 4px #0001;overflow:hidden;display:flex;flex-direction:column}.c img,.noimg{width:100%;height:200px;object-fit:cover;object-position:top;background:#f0eee6}
.noimg{display:flex;align-items:center;justify-content:center;color:#888;font-size:14px;gap:4px}.b{padding:14px}.b h3{margin:0 0 6px}.b p{margin:0 0 8px;font-size:14px}.m{font-size:12px;color:#777}a{color:#c15f3c}</style></head><body>
<header><h1>Awesome Claude Skills Gallery</h1><p>See what agent skills actually produce before you install them. <a href="https://github.com/Omrigotlieb/awesome-claude-skills-gallery">GitHub</a> · updated ${stars._updated ?? ''}</p>
<div class="f"><button class="on" data-c="all">All</button>${cats.map(c => `<button data-c="${esc(c)}">${esc(c)}</button>`).join('')}</div></header>
<main>${skills.map(s => `<div class="c" data-c="${esc(s.category)}">${img(s)}<div class="b"><h3><a href="${url(s)}">${esc(s.name)}</a></h3><p>${esc(s.desc)}</p><div class="m">${s.repo}${stars[s.repo] ? ` · ★ ${fmt(stars[s.repo].stars)}` : ''}${s.imageCredit ? `<br>${esc(s.imageCredit)}` : ''}</div></div></div>`).join('\n')}</main>
<script>document.querySelectorAll('.f button').forEach(b=>b.onclick=()=>{document.querySelectorAll('.f button').forEach(x=>x.classList.toggle('on',x===b));document.querySelectorAll('.c').forEach(c=>c.style.display=b.dataset.c==='all'||c.dataset.c===b.dataset.c?'':'none')})</script>
</body></html>
`;
fs.writeFileSync('docs/index.html', html);
console.log(`Built ${skills.length} skills in ${cats.length} categories`);
